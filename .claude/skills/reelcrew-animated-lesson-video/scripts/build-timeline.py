"""Lay scenes end-to-end from VO timing → src/timeline.js, audio/vo-track.wav, subtitles/<slug>.<lang>.srt (+ combined when bilingual).

Usage: build-timeline.py <project-dir>
Scene length = lead (0.6s; lesson.first_lead for scene 1 title card) + VO + tail (0.9s; 4s for the last scene end card).
lesson.thumbnail_intro > 0 prepends a silent 'thumb' scene (the thumbnail) and shifts everything after it.
"""
import json
import subprocess

import sys  # noqa: E402
sys.dont_write_bytecode = True  # keep the skill folder clean (no __pycache__ next to the scripts)
from lesson_common import load_lesson, project_dir, sub_langs, tool

DEFAULT_LEAD, TAIL, END_TAIL = 0.6, 0.9, 4.0
proj = project_dir()
lesson = load_lesson(proj)
langs = sub_langs(lesson)
vo = json.loads((proj / "audio/vo-timing.json").read_text())
intro = float(lesson.get("thumbnail_intro", 0) or 0)  # seconds of thumbnail shown before scene 1
chapter = {s["id"]: s.get("chapter") for s in lesson.get("scenes", []) if s.get("chapter")}  # scene names (Reelcrew Studio)
scenes, subs, t = ([{"id": "thumb", "start": 0.0, "dur": intro, "vo": None, "beats": []}] if intro else []), [], intro
for i, sc in enumerate(vo):
    lead = lesson.get("first_lead", 2.6) if i == 0 else DEFAULT_LEAD
    dur = round(lead + sc["duration"] + (END_TAIL if i == len(vo) - 1 else TAIL), 3)
    subs += [{**ln, "start": round(t + lead + ln["start"], 3), "end": round(t + lead + ln["end"], 3)} for ln in sc["lines"]]
    scenes.append({"id": sc["id"], **({"title": chapter[sc["id"]]} if sc["id"] in chapter else {}), "start": round(t, 3), "dur": dur, "vo": round(t + lead, 3),
                   "beats": [round(lead + ln["start"], 3) for ln in sc["lines"]]})
    t += dur
total = round(t, 3)
(proj / "src/timeline.js").write_text(
    "// Generated by build-timeline.py — do not edit by hand.\n"
    f"window.TIMELINE={json.dumps({'title': lesson.get('title', ''), 'watermark': lesson.get('watermark', ''), 'thumbnail': lesson.get('thumbnail', {}), 'sub_langs': langs, 'total': total, 'scenes': scenes, 'subs': subs}, ensure_ascii=False)};\n")

inputs, filters = [], []
voiced = [sc for sc in scenes if sc["vo"] is not None]
for k, sc in enumerate(voiced):
    inputs += ["-i", str(proj / f"audio/vo/{sc['id']}.mp3")]
    ms = int(sc["vo"] * 1000)
    filters.append(f"[{k}:a]aresample=44100,aformat=channel_layouts=stereo,adelay={ms}|{ms}[v{k}]")
filters.append("".join(f"[v{k}]" for k in range(len(voiced))) + f"amix=inputs={len(voiced)}:normalize=0,apad=whole_dur={total}[out]")
subprocess.run([tool("ffmpeg"), "-y", "-v", "error", *inputs, "-filter_complex", ";".join(filters), "-map", "[out]",
                "-t", str(total), str(proj / "audio/vo-track.wav")], check=True)


def ts(x: float) -> str:
    ms = int(round(x * 1000))
    return f"{ms // 3600000:02}:{ms // 60000 % 60:02}:{ms // 1000 % 60:02},{ms % 1000:03}"


(proj / "subtitles").mkdir(exist_ok=True)
formats = {lg: (lambda lg: lambda s: s[lg])(lg) for lg in langs}
if len(langs) > 1:
    formats["-".join(langs)] = lambda s: "\n".join(s[lg] for lg in langs)
for name, fmt in formats.items():
    # Each line stays 0.3 s after it is spoken, but never into the next line (players stack overlapping cues).
    ends = [min(s["end"] + 0.3, subs[k + 1]["start"] - 0.01) if k + 1 < len(subs) else s["end"] + 0.3 for k, s in enumerate(subs)]
    body = "\n".join(f"{i}\n{ts(s['start'])} --> {ts(ends[i - 1])}\n{fmt(s)}\n" for i, s in enumerate(subs, 1))
    (proj / f"subtitles/{lesson['slug']}.{name}.srt").write_text(body)
print(f"total {total}s, {len(scenes)} scenes, {len(subs)} subtitle lines")
for s in scenes:
    print(f"  {s['id']:<20} start {s['start']:7.2f}  dur {s['dur']:6.2f}  beats {s['beats']}")
